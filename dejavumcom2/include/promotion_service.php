2. 개인정보의 수집목적 및 이용목적<br>
3. 개인정보의 보유 및 이용기간<br>
<br><br>
1. 수집하는 개인정보의 항목<br>
<br><br>
회사는 회원가입, 원활한 고객상담, 각종 서비스의 제공을 위해 아래와 같은 개인정보를 수집하고 있습니다.<br>
<br>
1.1 수집항목 <br>
1)<br>
필수항목: 이름, 정품코드, 본인인증, 생일, 주소, 휴대폰번호, 이메일<br>
<br>
2)<br>
서비스 이용과정에서 IP주소, 쿠키, 방문일시, 서비스이용기록과 같은 정보가 자동으로 생성되어 수집될 수 있습니다.<br>
<br>
1.2 수집방법<br>
홈페이지 회원가입, 서면양식/전화/팩스를 통한 회원가입, 상담 게시판, 이메일, 배송요청, 생성정보 수집 툴<br>
<br><br>
2. 수집하는 개인정보 항목<br>
<br><br>
회사가 수집한 개인정보의 수집 및 이용 목적은 다음과 같으며 개인정보의 공유(목적 외 사용) 및 제3자에 대한 제공 규정)에 의한 경우를 제외하고는 타인에게 공개하지 않습니다.<br>
<br>
2.1<br>
성명, 생년월일, 정품코드, 본인인증: 서비스제공을 위한 계약의 성립(본인확인 및 본인의사 확인 등) 및 서비스이용에 따른 민원 처리를 위한 본인확인, 콘텐츠별 서비스의 제공 확인, 불량회원의 부정한 이용 재발 방지, 기타 소송이나 분쟁(민원신고 등)에 대한 대비<br>
<br>
2.2<br>
이메일 주소, 휴대폰번호: 고지사항 전달, 본인 의사 확인, 불만 처리 등 원활한 의사소통 경로의 확보, 새로운 서비스/신상품이나 이벤트 정보의 안내<br>
<br>
2.3<br>
회원의 신분증 사본 또는 이에 준하는 신분을 확인할 수 있는 증서 (회원이 미성년자인 경우 법정대리인 신분증 사본 또는 이에 준하는 신분을 확인할 수 있는 증서 포함): 회원의 권리보호 또는 회원과 회사간의 분쟁을 해결하기 위하여 본인임을 확인하여야 할 필요가 있는 경우에 이용<br>
<br>
2.4<br>
법정대리인의 이름, 연락처, 주소 및 이메일 주소: 청소년 회원의 회원가입시 동의 여부 확인, 법률상 미성년자의 법률행위에 대한 법정 대리인의 동의 또는 승인이 필요한 경우, 법정 대리인의 동의서로서 그 동의 또는 승인의 존재를 증명<br>
<br>
2.5<br>
IP 주소, 쿠키정보, 서비스이용기록 정보, 접속 로그: 사법기관의 통신사실확인자료 협조, 불량회원 및 해커 등 부정회원의 부정이용 등을 방지, 분쟁조정을 위한 기록보존, 불만처리 등 민원처리<br>
<br>
2.6<br>
그 외 선택항목: 개인정보 DB를 분석하여 더욱 향상된 양질의 서비스 기획 및 제공, 개인맞춤서비스를 제공하기 위한 자료<br>
<br><br>
