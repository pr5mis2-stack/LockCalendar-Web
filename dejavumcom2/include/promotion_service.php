주식회사 잉글리시에그(이하 ‘회사’)는 고객님의 개인정보를 중요시하며, 『개인정보 보호법』 및 『정보통신망 이용촉진 및 정보보호에 관한 법률』을 준수하고 있습니다. 회사는 개인정보 취급/처리 방침을 통하여 고객님께서 제공하시는 개인정보가 어떠한 용도와 방식으로 이용되고 있으며, 개인정보 보호를 위해 어떠한 조치가 취해지고 있는지 알려드립니다. 회사는 개인정보 취급/처리 방침을 개정하는 경우 웹사이트 공지사항(또는 개별공지)을 통하여 공지할 것입니다.
